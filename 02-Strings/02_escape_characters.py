
#Escape sequences characters 

#1) \n - New Line
letter = "Hello Sania, \nWelcome to Python Programming.\nThank you for joining the class !"
print(letter)

#2) \t - Tab
letter = "Hello Sania, \tWelcome to Python Programming.\tThank you for joining the class !"
print(letter)

#3) \\ - Blackslash - used to print a backslash in the string
letter = "Hello Sania, \\Welcome to Python Programming.\\Thank you for joining the class !"
print(letter)

#4) \' - Single Quote - used to print a single quote in the string
letter = "Hello Sania, \'Welcome to Python Programming.\' Thank you for joining the class !"
print(letter)

#5) \" - Double Quote - used to print a double quote in the string
letter = "Hello Sania, \"Welcome to Python Programming.\" Thank you for joining the class !"
print(letter)

#6) \; - Semicolon - used to print a semicolon in the string
letter = "Hello Sania,\;Welcome to Python Programming.\;Thank you for joining the class !" 
print(letter)


#use of all these escape sequences in a single string
letter = "Hello Sania,\n\tWelcome to \'Python Programming.\'\n\"Hello world !\" Thank you for joining the class !" 
print(letter)