#int 

age = 10 
print(age)
print(type(age))


#float 

height = 5.9
print(height)
print(type(height))


#string 

name = "Sania"
print(name)
print(type(name))


#boolean

is_adult = True
print(is_adult)
print(type(is_adult))

#none 

num = None 
print(num)
print(type(num))

#complex 

complex_num = 3 + 4j     #(real num + imaginary num (j)) == complex number
print(complex_num)
print(type(complex_num))


#list 

fruits = ["apple", "banana", "mango", "grapes"]
print(fruits)
print(type(fruits))

#tuple 

cars = ("BMW" ,"Audi" , "Ford")
print(cars)
print(type(cars))




