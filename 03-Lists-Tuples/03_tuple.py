#TUPLE INDEXING 

fruits = ("Apple", "Banana", "Mango")
print(fruits[0])
print(fruits[1])
print(fruits[2])


#TUPLE SLICING 

fruits = ("Apple", "Banana", "Mango", "Orange", "Strawberry")
print(fruits[0:3])
print(fruits[1:4])


#Tuple Slicing & skipping [start:stop:step

fruits = ("Apple", "Banana", "Mango", "Orange", "Strawberry")
print(fruits[0:5:2])
