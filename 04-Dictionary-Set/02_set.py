# Set
# A Set is a collection of unique elements.
# Sets do not allow duplicate values.

# Empty Set
s = set()
print(s)
print(type(s))


# Note:
# Don't use set = {} for an empty set.
# {} is used for an empty dictionary.
#
# Use s = set() for an empty set.


# Set with values
s = {1, 2, 3, 4}
print(s)
print(type(s))